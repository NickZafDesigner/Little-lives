interface NoteEvent {
  /** Beat within the pattern (0-based, quarter = 1). */
  t: number;
  /** MIDI note number. */
  n: number;
  /** Duration in beats. */
  d: number;
  /** Velocity 0-1. */
  v?: number;
}

interface Layer {
  wave: WaveKind;
  gain: number;
  soft?: boolean;
  /** Optional low-pass cutoff for softness. */
  cutoff?: number;
  notes: NoteEvent[];
}

interface Pattern {
  bars: number;
  layers: Layer[];
  /** Soft percussion hits at these beats. */
  ticks?: Array<{ t: number; kind: "tap" | "shush" | "softkick"; v?: number }>;
}

const MUTE_KEY = "ll_mute";

/** MIDI → Hz */
function hz(midi: number): number {
  return 440 * Math.pow(2, (midi - 69) / 12);
}

function loadMute(): boolean {
  try {
    return localStorage.getItem(MUTE_KEY) === "1";
  } catch {
    return false;
  }
}

function saveMute(muted: boolean) {
  try {
    localStorage.setItem(MUTE_KEY, muted ? "1" : "0");
  } catch {
    /* ignore */
  }
}

/** Soft decaying noise impulse for ConvolverNode reverb. */
function makeImpulse(ctx: AudioContext, seconds: number): AudioBuffer {
  const len = Math.max(1, Math.floor(ctx.sampleRate * seconds));
  const buf = ctx.createBuffer(2, len, ctx.sampleRate);
  for (let ch = 0; ch < 2; ch++) {
    const data = buf.getChannelData(ch);
    for (let i = 0; i < len; i++) {
      const env = Math.pow(1 - i / len, 2.4);
      data[i] = (Math.random() * 2 - 1) * env * (ch === 0 ? 1 : 0.92);
    }
  }
  return buf;
}

